import assert from 'node:assert/strict';
import { removeTopicTerm, preferenceChips, emptyState } from '../src/api.js';
import { persistentLibrary } from '../src/persistence.js';
assert.equal(removeTopicTerm('space exploration', 'space'), 'exploration');
assert.equal(removeTopicTerm('spacecraft space exploration', 'space'), 'spacecraft exploration');
assert.equal(removeTopicTerm('time travel and identity', 'time travel'), 'and identity');
const state=emptyState();
state.preferences.referenced_title='Interstellar';
assert.equal(preferenceChips(state).find(chip=>chip.field==='reference').text,'Like Interstellar');
const live={id:'book_bigbook_1',media_type:'book',title:'Live',source:'bigbook-api'};
const local={id:'book_local_1',media_type:'book',title:'Local',source:'local'};
const library={saved:[{item:live},{item:local}],conversations:[{id:'c',state:{selected_reference_id:live.id,last_recommendations:[live.id,local.id]},turns:[{results:{book:[{item:live},{item:local}]},choices:[live,local],title_matches:[{item:live},{item:local}],trace:{retrieval:{book:{on_demand_candidates:8},movie:{catalog_size:3}}}}]}]};
const persisted=persistentLibrary(library);
assert.deepEqual(persisted.saved.map(x=>x.item.id),[local.id]);
assert.equal(persisted.conversations[0].state.selected_reference_id,null);
assert.deepEqual(persisted.conversations[0].turns[0].results.book.map(x=>x.item.id),[local.id]);
assert.deepEqual(persisted.conversations[0].turns[0].choices.map(x=>x.id),[local.id]);
assert.deepEqual(Object.keys(persisted.conversations[0].turns[0].trace.retrieval),['movie']);
console.log('9 frontend context and API persistence checks passed');
