"""Cache source-provided Gutenberg summaries via Gutendex by exact ebook ID.

These summaries may be automatically generated by the SOURCE, not StoryScout.
They never supply publication years, page counts, language or genre facts.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
import csv
import gzip
import hashlib
import json
from pathlib import Path
import re
import sys
import time
import threading
import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.title_matching import title_key


def summary_record(row, expected):
    item_id = f"book_pg_{row.get('id')}"
    if item_id not in expected or row.get('copyright') is not False or 'en' not in row.get('languages', []):
        return None
    if title_key(row.get('title', '')) != title_key(expected[item_id]):
        return None
    summary = ' '.join(value.strip() for value in row.get('summaries', []) if isinstance(value, str) and value.strip())
    if len(summary) < 80:
        return None
    # Keep the source's generation disclosure in provenance rather than embedding it.
    summary = re.sub(r'\(?This is an automatically generated summary\.?\)?', '', summary, flags=re.I).strip()
    sentences = re.split(r'(?<=[.!?])\s+(?=[A-Z"“])', summary)
    excerpt = ' '.join(sentences[:2])[:650]
    return {'id': item_id, 'summary_text': summary[:2400], 'opening_excerpt': excerpt,
            'source': 'Project Gutenberg source-provided summary via Gutendex',
            'source_url': f"https://www.gutenberg.org/ebooks/{row['id']}",
            'api_url': f"https://gutendex.com/books/{row['id']}",
            'provenance': 'Source-generated summary; may contain errors; not independently verified; extractive opening shown',
            'usage_terms': 'Gutenberg public-domain-in-USA record (copyright=false); consult source ebook license and local law'}


def run(pages=64, offline=False):
    if not 1 <= pages <= 256:
        raise ValueError('pages must be between 1 and 256')
    cache = ROOT/'artifacts/.cache/book_summaries'
    cache.mkdir(parents=True, exist_ok=True)
    with (ROOT/'data/expanded/books.csv').open(encoding='utf-8', newline='') as stream:
        expected = {row['id']:row['title'] for row in csv.DictReader(stream) if row['id'].startswith('book_pg_')}
    # Cached public catalog pages work reliably where uncached multi-ID queries
    # may time out. IDs/title checks still restrict joins to our actual catalog.
    batches = list(range(1, pages+1))
    failures = []
    stop = threading.Event()

    def fetch(batch):
        path = cache/f'popular_page_{batch}.json'
        if path.exists():
            return json.loads(path.read_text())
        if offline:
            failures.append({'page':batch, 'error':'NotCached'})
            return {'results': []}
        if stop.is_set():
            failures.append({"page":batch, "error":"SkippedAfterRepeatedNetworkFailures"})
            return {"results": []}
        for attempt in range(2):
            try:
                response = httpx.get(f'https://gutendex.com/books/?page={batch}',
                                     headers={'User-Agent': 'StoryScoutCollegeNLP/3.0 (bounded academic catalog preparation)'},
                                     timeout=15, follow_redirects=True)
                response.raise_for_status()
                payload = response.json()
                path.write_text(json.dumps(payload))
                time.sleep(.5)
                return payload
            except (httpx.HTTPError, ValueError) as error:
                if attempt == 1:
                    failures.append({'page': batch, 'error': type(error).__name__})
                    if sum(x['error'] not in {'NotCached', 'SkippedAfterRepeatedNetworkFailures'} for x in failures) >= 6:
                        stop.set()
                else:
                    time.sleep(2)
        return {'results': []}

    records = {}
    with ThreadPoolExecutor(max_workers=2) as pool:
        for number, payload in enumerate(pool.map(fetch, batches), 1):
            for row in payload.get('results', []):
                record = summary_record(row, expected)
                if record:
                    records[record['id']] = record
            print(f'Book source batches {number}/{len(batches)}; {len(records)} summaries', flush=True)
    destination = ROOT/'data/enriched/book_summaries.csv.gz'
    # Resume without discarding summaries from earlier successful bounded runs.
    if destination.exists():
        with gzip.open(destination, 'rt', newline='') as stream:
            old = {row['id']:row for row in csv.DictReader(stream)}
        old.update(records)
        records = old
    if records:
        with gzip.open(destination.with_suffix('.tmp.gz'), 'wt', encoding='utf-8', newline='') as stream:
            writer = csv.DictWriter(stream, list(next(iter(records.values()))))
            writer.writeheader()
            writer.writerows(records[key] for key in sorted(records))
        destination.with_suffix('.tmp.gz').replace(destination)
    manifest = {'executed_at':datetime.now(timezone.utc).isoformat(), 'requested_pages':len(batches), 'catalog_book_records':len(expected),
                'stored_summaries':len(records), 'cache_only':offline, 'cached_pages':sum((cache/f'popular_page_{page}.json').exists() for page in batches), 'failed_batches':failures,
                'identity_join':'exact Gutenberg ebook ID and normalized source title; English and copyright=false',
                'generation':'Source-provided automatic summaries, not independent plot verification or StoryScout generation',
                'source':'https://gutendex.com/', 'runtime_network_calls':False}
    (ROOT/'data/enriched/book_summaries_manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print(json.dumps(manifest), flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pages', type=int, default=64, help='Bound public catalog requests; pages are cached for replay')
    parser.add_argument('--offline', action='store_true', help='Replay cached public responses without external calls')
    args=parser.parse_args()
    run(args.pages, args.offline)
